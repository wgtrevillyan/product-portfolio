/**
 * Build-time analytics injector (idempotent).
 *
 * Adds PostHog (the analytics stack) plus a small AI-referral helper to every site HTML page's
 * <head>. The helper detects visitors arriving from AI answer engines and fires an `ai_referral`
 * event + `ai_source` super-property to PostHog. (Mixpanel and LogRocket were removed — PostHog,
 * including its session replay, is now the single analytics stack.)
 *
 * The PostHog project token is read from NEXT_PUBLIC_POSTHOG_TOKEN at build time (it's a
 * public client-side key, injected here rather than committed by hand). Host defaults to the
 * first-party `/ingest` reverse proxy (see vercel.json rewrites → *.i.posthog.com) so browser
 * ad/tracking blockers can't drop events to a `*.posthog.com` host — important for capturing
 * referral/UTM traffic. Override with NEXT_PUBLIC_POSTHOG_HOST. With no token (e.g. local
 * builds) PostHog is skipped and nothing breaks.
 *
 * Runs in `npm run build` BEFORE the page generators, so the detail_*.html templates carry the
 * snippet and the generated product/company/patent pages inherit it.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PH_TOKEN = process.env.NEXT_PUBLIC_POSTHOG_TOKEN || '';
const PH_HOST = process.env.NEXT_PUBLIC_POSTHOG_HOST || '/ingest';

const MARKER = 'data-generated="analytics"';
const STRIP_RE = /[ \t]*<!-- PostHog \+ AI-referral[\s\S]*?<script data-generated="analytics">[\s\S]*?<\/script>\n?/g;

function block() {
  // Standard PostHog array-stub loader (only initialized when a token is present).
  const phLoader = PH_TOKEN
    ? `  if(PH_TOKEN){!function(t,e){var o,n,p,r;e.__SV||(window.posthog=e,e._i=[],e.init=function(i,s,a){function g(t,e){var o=e.split(".");2==o.length&&(t=t[o[0]],e=o[1]),t[e]=function(){t.push([e].concat(Array.prototype.slice.call(arguments,0)))}}(p=t.createElement("script")).type="text/javascript",p.crossOrigin="anonymous",p.async=!0,p.src=s.api_host.replace(".i.posthog.com","-assets.i.posthog.com")+"/static/array.js",(r=t.getElementsByTagName("script")[0]).parentNode.insertBefore(p,r);var u=e;for(void 0!==a?u=e[a]=[]:a="posthog",u.people=u.people||[],u.toString=function(t){var e="posthog";return"posthog"!==a&&(e+="."+a),t||(e+=" (stub)"),e},u.people.toString=function(){return u.toString(1)+".people (stub)"},o="init capture register register_once unregister identify setPersonProperties group reset get_distinct_id alias set_config opt_in_capturing opt_out_capturing".split(" "),n=0;n<o.length;n++)g(u,o[n]);e._i.push([i,s,a])},e.__SV=1)}(document,window.posthog||[]);posthog.init(PH_TOKEN,{api_host:PH_HOST,ui_host:"https://us.posthog.com",person_profiles:"identified_only"});}`
    : '  /* no NEXT_PUBLIC_POSTHOG_TOKEN at build time — PostHog skipped */';

  return `  <!-- PostHog + AI-referral analytics (generated by scripts/inject-analytics.js — do not edit by hand) -->
  <script ${MARKER}>
  (function(){
    var PH_TOKEN=${JSON.stringify(PH_TOKEN)};
    var PH_HOST=${JSON.stringify(PH_HOST)};
${phLoader}
    function aiSource(){
      try{
        var host="";try{host=new URL(document.referrer).hostname;}catch(e){}
        var refs=[[/chatgpt\\.com|chat\\.openai\\.com/,"chatgpt"],[/perplexity\\.ai/,"perplexity"],[/claude\\.ai/,"claude"],[/gemini\\.google\\.com|bard\\.google\\.com/,"gemini"],[/copilot\\.microsoft\\.com/,"copilot"]];
        for(var i=0;i<refs.length;i++){if(refs[i][0].test(host))return refs[i][1];}
        var q=new URLSearchParams(location.search),u=((q.get("utm_source")||q.get("ref")||"")+"").toLowerCase();
        var known=["chatgpt","openai","perplexity","claude","anthropic","gemini","copilot"];
        for(var j=0;j<known.length;j++){if(u.indexOf(known[j])>-1)return known[j];}
        return null;
      }catch(e){return null;}
    }
    function fire(){
      var src=aiSource();if(!src)return;
      var props={ai_source:src,landing_path:location.pathname};
      try{if(window.posthog&&PH_TOKEN){posthog.register({ai_source:src});posthog.capture("ai_referral",props);}}catch(e){}
    }
    if(document.readyState!=="loading")fire();else document.addEventListener("DOMContentLoaded",fire);
  })();
  </script>
`;
}

function main() {
  const files = fs
    .readdirSync(ROOT)
    .filter((f) => f.endsWith('.html'))
    .sort();
  let n = 0;
  const snippet = block();
  for (const f of files) {
    const file = path.join(ROOT, f);
    let html = fs.readFileSync(file, 'utf8');
    if (!/<\/head>/i.test(html)) continue;
    html = html.replace(STRIP_RE, ''); // idempotent: drop any prior injected block
    html = html.replace(/<\/head>/i, `${snippet}</head>`);
    fs.writeFileSync(file, html, 'utf8');
    n++;
  }
  console.log(`inject-analytics: injected PostHog + AI-referral into ${n} HTML file(s)${PH_TOKEN ? '' : ' (no PostHog token — analytics disabled)'}`);
}

main();
